test('live app bridge answers values, tables, KPIs and image files, and wraps pages with the SDK', () => {
  const { applyMutation } = require('../shared/domain.mjs');
  const { bridgeRead } = require('../src/bridge.js');
  const { withSdk } = require('../src/rw-sdk.js');
  const { STARTER_APP } = require('../src/app-templates.js');
  let s = makeFixture(); const pid = 'research-project';
  s = applyMutation(s, { type:'note', projectId:pid, value:{ id:'sh1', title:'Budget', kind:'sheet', content:'Item,Cost\nAds,100\nTools,=B2/2', author:'You', createdAt:'x', updatedAt:'x' } });
  s = applyMutation(s, { type:'artifact', projectId:pid, value:{ id:'db1', kind:'database', title:'Leads', data:{ properties:[{ id:'pn', name:'Name', type:'title' }, { id:'pv', name:'Value', type:'number' }], rows:[{ id:'r1', cells:{ pn:'A', pv:30 } }], views:[{ id:'v', type:'table' }] } } });
  s = applyMutation(s, { type:'ref', projectId:pid, value:{ id:'r_cost', name:'cost', target:{ type:'cell', noteId:'sh1', range:'B3' } } });
  s = applyMutation(s, { type:'project:update', projectId:pid, value:{ kpis:[{ id:'k1', label:'Spend', value:'', unit:'$', target:'200', formula:'={{cost}} * 2' }] } });
  const p = { ...s.projects[0], files:[{ id:'f1', name:'map.PNG', storedName:'f1.png', size:10 }, { id:'f2', name:'brief.pdf', storedName:'f2.pdf', size:5 }] };
  assert.equal(bridgeRead(p, 'get', ['cost']), 50);
  assert.throws(() => bridgeRead(p, 'get', ['ghost']), /Unknown reference/);
  assert.deepEqual(bridgeRead(p, 'kpis')[0], { id:'k1', label:'Spend', value:100, unit:'$', target:'200' });
  const sheet = bridgeRead(p, 'table', ['budget']); assert.equal(sheet.rows[1].values.Cost, 50);
  const db = bridgeRead(p, 'table', ['Leads']); assert.deepEqual(db.rows[0].values, { Name:'A', Value:30 });
  assert.deepEqual(bridgeRead(p, 'tables').map(t => t.name).sort(), ['Budget', 'Leads']);
  assert.deepEqual(bridgeRead(p, 'files').map(f => f.id), ['f1']);
  assert.throws(() => bridgeRead(p, 'table', ['nothing']), /No database or spreadsheet/);
  assert.throws(() => bridgeRead(p, 'deleteEverything', []), /Unknown request/);
  const page = withSdk('<!DOCTYPE html><html><head><title>x</title></head><body>hi</body></html>');
  assert.ok(page.startsWith('<!doctype html>') && (page.match(/<!doctype/gi) || []).length === 1 && page.includes('window.rw={') && page.includes('hi</body>'));
  assert.ok(page.indexOf('window.rw') < page.indexOf('<title>x'));
  const starter = withSdk(STARTER_APP).match(/<script>([\s\S]*?)<\/script>/g); assert.equal(starter.length, 1); new Function(starter[0].replace(/<\/?script>/g, ''));
});
