  assert.ok(prompts[0].includes('{{visits}} = 42') && prompts[0].includes('{{ghost}} could not be read') && prompts[0].includes('rw.state.set'));
  assert.ok(prompts[0].includes('"label":"Visits","value":"42"'));
  const app = store.state.projects[0].artifacts.find(a => a.id === 'app1');
  assert.equal(app.data.html, '<p>new</p>'); assert.deepEqual(app.data.state, { best: 9 });
